(() => {
  'use strict';
  const root = document.documentElement;
  let language = root.dataset.language === 'zh' ? 'zh' : 'en';
  const policyText = {
    on: {en: ['The behavior and target policies are the same.', 'The current policy π collects a trajectory τ.', 'The target policy learns from its own experience.'], zh: ['行为策略与目标策略相同。', '当前策略 π 收集一条轨迹 τ。', '目标策略从自己的经验中学习。']},
    off: {en: ['Behavior π and target π′ may differ.', 'The behavior policy π collects a trajectory τ.', 'The target policy π′ learns from experience generated by another policy.'], zh: ['行为策略 π 与目标策略 π′ 可以不同。', '行为策略 π 收集一条轨迹 τ。', '目标策略 π′ 从另一种策略产生的经验中学习。']}
  };
  const loggingText = {en: ['Persist the log before its corresponding data page reaches disk.', 'The modified data page can be written back later.', 'After a crash, recovery uses the log to redo or undo the relevant changes.'], zh: ['对应的数据页写回磁盘之前，先持久化日志。', '修改过的数据页可以稍后再写回磁盘。', '发生崩溃后，恢复过程依据日志，重做或撤销相应修改。']};
  const demos = [...document.querySelectorAll('[data-policy-demo], [data-logging-demo]')];
  function renderDemo(demo) {
    const step = Number(demo.dataset.step || 0), mode = demo.dataset.mode || 'on', isPolicy = demo.hasAttribute('data-policy-demo');
    demo.querySelectorAll('[data-node]').forEach(node => node.classList.toggle('is-active', Number(node.dataset.node) === step));
    demo.querySelector('[data-demo-caption]').textContent = isPolicy ? policyText[mode][language][step] : loggingText[language][step];
    demo.querySelector('[data-step-label]').textContent = `${step + 1} / 3`;
    if (isPolicy) {demo.querySelector('[data-target-symbol]').textContent = mode === 'on' ? 'π' : 'π′'; demo.querySelectorAll('[data-policy-mode]').forEach(button => button.setAttribute('aria-pressed', String(button.dataset.policyMode === mode)));}
  }
  demos.forEach(demo => {
    renderDemo(demo);
    demo.addEventListener('click', event => {
      const mode = event.target.closest('button[data-policy-mode]');
      if (mode) { demo.dataset.mode = mode.dataset.policyMode; demo.dataset.step = '0'; }
      else if (event.target.closest('button[data-demo-next]')) demo.dataset.step = String((Number(demo.dataset.step) + 1) % 3);
      else if (event.target.closest('button[data-demo-previous]')) demo.dataset.step = String((Number(demo.dataset.step) + 2) % 3);
      else return;
      renderDemo(demo);
    });
  });
  const contents = document.querySelector('[data-contents]');
  let headingObserver;
  function renderContents() {
    const prose = document.querySelector(`[data-article-language="${language}"]`); if (!prose) return;
    const wordCount = language === 'zh' ? prose.textContent.replace(/\s/g, '').length : prose.textContent.trim().split(/\s+/).length;
    const minutes = Math.max(1, Math.ceil(wordCount / (language === 'zh' ? 450 : 220)));
    const time = document.querySelector('[data-reading-time]'); if (time) time.textContent = language === 'zh' ? `约 ${minutes} 分钟` : `${minutes} min read`;
    if (!contents) return; if (headingObserver) headingObserver.disconnect(); contents.replaceChildren();
    const headings = [...prose.querySelectorAll('h2, h3')];
    if (!headings.length) {const link = document.createElement('a'); prose.id = `article-start-${language}`; link.href = `#${prose.id}`; link.textContent = language === 'zh' ? '正文' : 'The note'; contents.append(link); return;}
    headings.forEach((heading, i) => {
      if (language === 'zh' && !heading.id.startsWith('zh-')) heading.id = `zh-${heading.id || i + 1}`;
      if (!heading.id) heading.id = `section-${i + 1}`;
      const link = document.createElement('a'); link.href = `#${heading.id}`; link.textContent = heading.textContent; link.dataset.level = heading.tagName === 'H3' ? '3' : '2'; contents.append(link);
    });
    if ('IntersectionObserver' in window) {headingObserver = new IntersectionObserver(entries => {const visible = entries.find(entry => entry.isIntersecting); if (!visible) return; contents.querySelectorAll('a').forEach(link => link.setAttribute('aria-current', String(link.hash.slice(1) === visible.target.id)));}, {rootMargin: '-5% 0px -75% 0px'}); headings.forEach(h => headingObserver.observe(h));}
  }
  const filterButtons = [...document.querySelectorAll('[data-topic-filter]')]; let topic = 'all';
  function renderFilter() {
    let count = 0; document.querySelectorAll('[data-note-tags]').forEach(note => {let tags = []; try {tags = JSON.parse(note.dataset.noteTags);} catch (_) {} const visible = topic === 'all' || tags.includes(topic); note.hidden = !visible; if (visible) count++;});
    filterButtons.forEach(button => button.setAttribute('aria-pressed', String(button.dataset.topicFilter === topic)));
    const result = document.querySelector('[data-filter-result]'); if (result) result.textContent = topic === 'all' ? '' : language === 'zh' ? `${count} 篇笔记` : `${count} ${count === 1 ? 'note' : 'notes'}`;
  }
  filterButtons.forEach(button => button.addEventListener('click', () => {topic = button.dataset.topicFilter; renderFilter();}));
  function setLanguage(next, remember) {
    const previous = language; language = next === 'zh' ? 'zh' : 'en'; root.dataset.language = language; root.lang = language === 'zh' ? 'zh-CN' : 'en';
    document.querySelectorAll('[data-set-language]').forEach(button => button.setAttribute('aria-pressed', String(button.dataset.setLanguage === language)));
    if (remember) {try {localStorage.setItem('pinlog-language', language);} catch (_) {}}
    demos.forEach(renderDemo); renderContents(); renderFilter();
    if (previous !== language && window.MathJax && window.MathJax.Hub) window.MathJax.Hub.Queue(['Typeset', window.MathJax.Hub]);
  }
  document.querySelectorAll('[data-set-language]').forEach(button => button.addEventListener('click', () => setLanguage(button.dataset.setLanguage, true)));
  document.querySelectorAll('.article-prose table').forEach(table => {const wrapper = document.createElement('div'); wrapper.className = 'table-scroll'; table.before(wrapper); wrapper.append(table);});
  setLanguage(language, false);
})();
